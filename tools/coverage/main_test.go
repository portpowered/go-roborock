package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const (
	testFilePermissions      = 0o600
	testDirectoryPermissions = 0o700
)

func TestGeneratedFile(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	handwritten := filepath.Join(dir, "hand.go")
	generated := filepath.Join(dir, "generated.go")

	writeTestFile(t, handwritten, "package sample\n")

	writeTestFile(t, generated, "// Code generated by a tool. DO NOT EDIT.\npackage sample\n")

	for filename, want := range map[string]bool{
		handwritten:     false,
		generated:       true,
		"models.gen.go": true,
	} {
		got, err := generatedFile(filename)
		if err != nil {
			t.Fatal(err)
		}

		if got != want {
			t.Errorf("generatedFile(%q) = %v, want %v", filename, got, want)
		}
	}
}

func TestReportUsesStatementWeightsAndExcludesGeneratedFiles(t *testing.T) {
	t.Parallel()

	dir := setupCoverageDirectory(t, coverageProfile())

	err := report(dir, "coverage.out", 40, false, "filtered.out")
	if err != nil {
		t.Fatalf("40%% should pass: %v", err)
	}

	assertFilteredProfile(t, dir)

	err = report(dir, "coverage.out", 41, false, "")
	if err == nil {
		t.Fatal("41% should fail")
	}
}

func TestReportMergesDuplicateCoverageBlocks(t *testing.T) {
	t.Parallel()

	profile := coverageProfile()
	profile += "example.com/test/pkg/sample/client.go:1.1,1.2 4 0\n"
	profile += "example.com/test/pkg/sample/client.go:2.1,2.2 6 1\n"
	dir := setupCoverageDirectory(t, profile)

	err := report(dir, "coverage.out", 100, false, "filtered.out")
	if err != nil {
		t.Fatalf("duplicate blocks should merge to 100%%: %v", err)
	}

	assertFilteredProfile(t, dir)
	// #nosec G304 -- dir is created by t.TempDir and the filename is fixed.
	filtered, err := os.ReadFile(filepath.Join(dir, "filtered.out"))
	if err != nil {
		t.Fatal(err)
	}

	if strings.Count(string(filtered), "client.go:") != 2 {
		t.Fatalf("filtered profile did not deduplicate blocks: %s", filtered)
	}
}

func setupCoverageDirectory(t *testing.T, profile string) string {
	t.Helper()
	dir := t.TempDir()

	err := os.MkdirAll(filepath.Join(dir, "pkg/sample"), testDirectoryPermissions)
	if err != nil {
		t.Fatal(err)
	}

	err = os.MkdirAll(filepath.Join(dir, "pkg/testing"), testDirectoryPermissions)
	if err != nil {
		t.Fatal(err)
	}

	files := map[string]string{
		"go.mod":                   "module example.com/test\n",
		"pkg/sample/client.go":     "package sample\n",
		"pkg/sample/models.gen.go": "// Code generated by a tool. DO NOT EDIT.\npackage sample\n",
		"pkg/testing/helper.go":    "package testing\n",
	}
	for name, contents := range files {
		writeTestFile(t, filepath.Join(dir, name), contents)
	}

	writeTestFile(t, filepath.Join(dir, "coverage.out"), profile)

	return dir
}

func coverageProfile() string {
	return strings.Join([]string{
		"mode: set",
		"example.com/test/pkg/sample/client.go:1.1,1.2 4 1",
		"example.com/test/pkg/sample/client.go:2.1,2.2 6 0",
		"example.com/test/pkg/sample/models.gen.go:1.1,1.2 100 0",
		"example.com/test/pkg/testing/helper.go:1.1,1.2 100 0",
	}, "\n") + "\n"
}

func assertFilteredProfile(t *testing.T, dir string) {
	t.Helper()
	// #nosec G304 -- dir is created by t.TempDir and the filename is fixed.
	filtered, err := os.ReadFile(filepath.Join(dir, "filtered.out"))
	if err != nil {
		t.Fatal(err)
	}

	filteredText := string(filtered)

	if strings.Contains(filteredText, "models.gen.go") || strings.Contains(filteredText, "helper.go") {
		t.Fatalf("filtered profile includes excluded records: %s", filtered)
	}

	if !strings.Contains(filteredText, "client.go") {
		t.Fatalf("filtered profile omits client records: %s", filtered)
	}
}

func writeTestFile(t *testing.T, filename, contents string) {
	t.Helper()

	err := os.WriteFile(filename, []byte(contents), testFilePermissions)
	if err != nil {
		t.Fatal(err)
	}
}
